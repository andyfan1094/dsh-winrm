export type WinKey = keyof typeof zh

/** Translate a key in one dictionary with optional {name} params. */
export function t(dict: Record<string, string>, key: WinKey, values?: Record<string, string | number>): string {
  let text = dict[key] ?? key
  if (values !== undefined) {
    for (const [name, value] of Object.entries(values)) {
      text = text.split('{' + name + '}').join(String(value))
    }
  }
  return text
}
